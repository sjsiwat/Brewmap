import cafeData from "@/data/cafes.json";
import { haversineKm, type LatLng } from "@/lib/geo";

export type DrinkType = "Coffee" | "Tea" | "Non-Coffee";

export interface Cafe {
  slug: string;
  index: string;
  name: string;
  area: string;
  address: string;
  specialty: string;
  /** Free-text tasting description, for display only. */
  flavor: string;
  atmosphere: string;
  /** Typical drink price in THB. */
  priceAvg: number;
  tags: string[];
  hours: string;
  rating: number;
  reviewCount: number;
  petFriendly: boolean;
  parking: boolean;
  drinkType: DrinkType;
  lat: number;
  lng: number;
}

// Real Chiang Mai cafe data sourced from Google Maps
// (via gosom/google-maps-scraper, scraped Oct 2026) across Nimman, Old City,
// Santitham/Chang Phueak, the Ping riverside, Wat Ket, Chang Khlan, Hang Dong,
// Fa Ham, Suthep/CMU, and outlying districts (Mae Rim, Tha Sala, San Phi Suea).
// name / address / lat / lng / hours / rating / reviewCount are real listing data.
// specialty / flavor / atmosphere / tags / petFriendly / parking / drinkType /
// priceAvg are AI-derived from real customer review text - treat as a
// seed dataset to refine with owners/manual QA before shipping to prod.
// Generated by scripts/scrape-cafes/build_cafes_full.py -> data/cafes.json.
export const cafes = cafeData as Cafe[];

export function formatPrice(priceAvg: number): string {
  return `~${priceAvg}฿`;
}

export function distanceToCafe(origin: LatLng, cafe: Cafe): number {
  return haversineKm(origin, { lat: cafe.lat, lng: cafe.lng });
}

