export function osmEmbedUrl(lat: number, lng: number, delta = 0.006): string {
  const bbox = `${lng - delta}%2C${lat - delta}%2C${lng + delta}%2C${lat + delta}`;
  return `https://www.openstreetmap.org/export/embed.html?bbox=${bbox}&layer=mapnik&marker=${lat}%2C${lng}`;
}

export function osmViewUrl(lat: number, lng: number): string {
  return `https://www.openstreetmap.org/?mlat=${lat}&mlon=${lng}#map=16/${lat}/${lng}`;
}

export interface MatchContext {
  /** Distance from the user's current origin, in km. */
  distanceKm: number;
}

export interface MatchOption {
  label: string;
  test?: (cafe: Cafe, ctx: MatchContext) => boolean;
}

export const priceOptions: MatchOption[] = [
  { label: "Any" },
  { label: "Under 100฿", test: (c) => c.priceAvg < 100 },
  { label: "100–140฿", test: (c) => c.priceAvg >= 100 && c.priceAvg <= 140 },
  { label: "Over 140฿", test: (c) => c.priceAvg > 140 },
];

export const distanceOptions: MatchOption[] = [
  { label: "Any" },
  { label: "Under 3 km", test: (_, { distanceKm }) => distanceKm < 3 },
  { label: "3–8 km", test: (_, { distanceKm }) => distanceKm >= 3 && distanceKm <= 8 },
  { label: "Over 8 km", test: (_, { distanceKm }) => distanceKm > 8 },
];

export const parkingOptions: MatchOption[] = [
  { label: "Any" },
  { label: "Parking required", test: (c) => c.parking },
];

export const drinkTypeOptions: MatchOption[] = [
  { label: "Any" },
  { label: "Coffee", test: (c) => c.drinkType === "Coffee" },
  { label: "Tea", test: (c) => c.drinkType === "Tea" },
  { label: "Non-Coffee", test: (c) => c.drinkType === "Non-Coffee" },
];
